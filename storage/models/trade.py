"""
Database models for trade logging and tracking.
"""
from datetime import datetime
from typing import Optional
from sqlalchemy import String, Float, Integer, DateTime, Boolean, Text, Enum as SQLEnum
from sqlalchemy.orm import Mapped, mapped_column
from enum import Enum

from storage.database import Base


class SignalDirection(str, Enum):
    LONG = "long"
    SHORT = "short"


class SignalStatus(str, Enum):
    PENDING = "pending"
    EXECUTED = "executed"
    REJECTED = "rejected"
    EXPIRED = "expired"


class OrderSide(str, Enum):
    BUY = "buy"
    SELL = "sell"


class OrderStatus(str, Enum):
    PENDING = "pending"
    SUBMITTED = "submitted"
    FILLED = "filled"
    PARTIAL = "partial"
    CANCELLED = "cancelled"
    REJECTED = "rejected"


class Signal(Base):
    """Trading signal generated by strategies"""
    __tablename__ = "signals"

    id: Mapped[int] = mapped_column(primary_key=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    symbol: Mapped[str] = mapped_column(String(10))
    strategy: Mapped[str] = mapped_column(String(50))
    direction: Mapped[str] = mapped_column(String(10))
    confidence: Mapped[float] = mapped_column(Float)
    entry_price: Mapped[float] = mapped_column(Float)
    stop_loss: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    take_profit: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    status: Mapped[str] = mapped_column(String(20), default="pending")

    # AI evaluation
    ai_evaluated: Mapped[bool] = mapped_column(Boolean, default=False)
    ai_decision: Mapped[Optional[str]] = mapped_column(String(20), nullable=True)
    ai_reasoning: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Market context at signal time
    market_price: Mapped[float] = mapped_column(Float)
    volume: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    rsi: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    atr: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    # Correlation tracking
    correlation_id: Mapped[Optional[str]] = mapped_column(String(36), nullable=True)


class Trade(Base):
    """Executed trade records"""
    __tablename__ = "trades"

    id: Mapped[int] = mapped_column(primary_key=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    symbol: Mapped[str] = mapped_column(String(10))
    side: Mapped[str] = mapped_column(String(10))
    quantity: Mapped[int] = mapped_column(Integer)
    price: Mapped[float] = mapped_column(Float)
    value: Mapped[float] = mapped_column(Float)

    # Order info
    order_id: Mapped[str] = mapped_column(String(50))
    alpaca_order_id: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    status: Mapped[str] = mapped_column(String(20))

    # Strategy link
    strategy: Mapped[str] = mapped_column(String(50))
    signal_id: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)

    # Fees and slippage
    commission: Mapped[float] = mapped_column(Float, default=0.0)
    slippage: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    # Extended hours
    extended_hours: Mapped[bool] = mapped_column(Boolean, default=False)

    # Correlation tracking
    correlation_id: Mapped[Optional[str]] = mapped_column(String(36), nullable=True)


class Position(Base):
    """Current open positions"""
    __tablename__ = "positions"

    id: Mapped[int] = mapped_column(primary_key=True)
    symbol: Mapped[str] = mapped_column(String(10), unique=True)
    quantity: Mapped[int] = mapped_column(Integer)
    avg_entry_price: Mapped[float] = mapped_column(Float)
    current_price: Mapped[float] = mapped_column(Float)
    market_value: Mapped[float] = mapped_column(Float)
    unrealized_pnl: Mapped[float] = mapped_column(Float)
    unrealized_pnl_pct: Mapped[float] = mapped_column(Float)

    # Risk management
    stop_loss: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    take_profit: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    trailing_stop: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    # Tracking
    strategy: Mapped[str] = mapped_column(String(50))
    opened_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    last_updated: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Time-based stop
    time_stop: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)


class DailySummary(Base):
    """Daily trading performance summary"""
    __tablename__ = "daily_summaries"

    id: Mapped[int] = mapped_column(primary_key=True)
    date: Mapped[datetime] = mapped_column(DateTime)

    # Portfolio snapshot
    starting_equity: Mapped[float] = mapped_column(Float)
    ending_equity: Mapped[float] = mapped_column(Float)
    high_water_mark: Mapped[float] = mapped_column(Float)

    # Trade stats
    total_trades: Mapped[int] = mapped_column(Integer, default=0)
    winning_trades: Mapped[int] = mapped_column(Integer, default=0)
    losing_trades: Mapped[int] = mapped_column(Integer, default=0)

    # P&L
    gross_pnl: Mapped[float] = mapped_column(Float, default=0.0)
    net_pnl: Mapped[float] = mapped_column(Float, default=0.0)
    commissions: Mapped[float] = mapped_column(Float, default=0.0)

    # Performance metrics
    win_rate: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    profit_factor: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    avg_win: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    avg_loss: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    max_drawdown: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    # Signal stats
    signals_generated: Mapped[int] = mapped_column(Integer, default=0)
    signals_executed: Mapped[int] = mapped_column(Integer, default=0)
    ai_approvals: Mapped[int] = mapped_column(Integer, default=0)
    ai_rejections: Mapped[int] = mapped_column(Integer, default=0)

    # Risk stats
    max_positions_held: Mapped[int] = mapped_column(Integer, default=0)
    max_portfolio_heat: Mapped[Optional[float]] = mapped_column(Float, nullable=True)


class AIDecisionLog(Base):
    """Log of AI decisions for analysis"""
    __tablename__ = "ai_decision_logs"

    id: Mapped[int] = mapped_column(primary_key=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    symbol: Mapped[str] = mapped_column(String(10))
    signal_id: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)

    # Request context
    request_context: Mapped[str] = mapped_column(Text)  # JSON
    web_search_used: Mapped[bool] = mapped_column(Boolean, default=False)

    # Decision
    decision: Mapped[str] = mapped_column(String(20))
    confidence: Mapped[float] = mapped_column(Float)
    reasoning: Mapped[str] = mapped_column(Text)

    # Modifications suggested
    modified_stop: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    modified_target: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    modified_size: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    # Timing
    response_time_ms: Mapped[int] = mapped_column(Integer)
    tokens_used: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)

    # Correlation
    correlation_id: Mapped[Optional[str]] = mapped_column(String(36), nullable=True)
