"""
Base strategy interface and signal definitions.
"""
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime
from typing import Dict, Any, Optional, List, Set
from enum import Enum
import uuid


class SignalDirection(str, Enum):
    LONG = "long"
    SHORT = "short"


class SignalType(str, Enum):
    ENTRY = "entry"
    EXIT = "exit"
    SCALE_IN = "scale_in"
    SCALE_OUT = "scale_out"


class SignalStrength(str, Enum):
    WEAK = "weak"
    MODERATE = "moderate"
    STRONG = "strong"
    VERY_STRONG = "very_strong"


class AssetClass(str, Enum):
    STOCK = "us_equity"
    CRYPTO = "crypto"


@dataclass
class Signal:
    """
    Trading signal generated by a strategy.
    """
    symbol: str
    direction: SignalDirection
    signal_type: SignalType
    strategy: str
    timestamp: datetime = field(default_factory=datetime.now)

    # Confidence and strength
    confidence: float = 0.5  # 0-1
    strength: SignalStrength = SignalStrength.MODERATE

    # Price targets
    entry_price: Optional[float] = None
    stop_loss: Optional[float] = None
    take_profit: Optional[float] = None
    risk_reward_ratio: Optional[float] = None

    # Position sizing hint
    suggested_size_pct: Optional[float] = None  # Percent of equity

    # Context for AI
    reasoning: str = ""
    indicators_used: Dict[str, float] = field(default_factory=dict)
    market_context: Dict[str, Any] = field(default_factory=dict)

    # Tracking
    signal_id: str = field(default_factory=lambda: str(uuid.uuid4())[:8])
    correlation_id: Optional[str] = None

    # Expiration
    valid_until: Optional[datetime] = None

    # Asset class (stock or crypto)
    asset_class: AssetClass = AssetClass.STOCK

    def __post_init__(self):
        # Calculate R:R if we have entry, stop, and target
        if self.entry_price and self.stop_loss and self.take_profit:
            risk = abs(self.entry_price - self.stop_loss)
            reward = abs(self.take_profit - self.entry_price)
            if risk > 0:
                self.risk_reward_ratio = reward / risk

    @property
    def is_buy(self) -> bool:
        return self.direction == SignalDirection.LONG

    @property
    def is_sell(self) -> bool:
        return self.direction == SignalDirection.SHORT

    @property
    def is_expired(self) -> bool:
        if self.valid_until is None:
            return False
        return datetime.now() > self.valid_until

    def to_dict(self) -> Dict[str, Any]:
        return {
            'signal_id': self.signal_id,
            'symbol': self.symbol,
            'direction': self.direction.value,
            'signal_type': self.signal_type.value,
            'strategy': self.strategy,
            'confidence': self.confidence,
            'strength': self.strength.value,
            'entry_price': self.entry_price,
            'stop_loss': self.stop_loss,
            'take_profit': self.take_profit,
            'risk_reward_ratio': self.risk_reward_ratio,
            'reasoning': self.reasoning,
            'indicators': self.indicators_used,
            'timestamp': self.timestamp.isoformat(),
            'asset_class': self.asset_class.value
        }


@dataclass
class StrategyConfig:
    """Configuration for a strategy - AGGRESSIVE DEFAULTS"""
    name: str
    enabled: bool = True
    symbols: Set[str] = field(default_factory=set)  # Empty = all symbols

    # Confidence thresholds - LOWERED FOR AGGRESSIVE TRADING
    min_confidence: float = 0.40  # Lowered from 0.6 - generate more signals
    ai_threshold: float = 0.55  # Lowered from 0.8 - more signals get through

    # Risk parameters - INCREASED FOR AGGRESSIVE TRADING
    max_position_pct: float = 0.05  # Increased from 0.02 - 5% per position
    default_stop_atr_mult: float = 2.5  # Wider stops to avoid getting stopped out
    default_target_atr_mult: float = 3.5  # Better R:R

    # Time filters
    trade_premarket: bool = True
    trade_regular: bool = True
    trade_afterhours: bool = False

    # Strategy-specific params
    params: Dict[str, Any] = field(default_factory=dict)


class Strategy(ABC):
    """
    Base class for all trading strategies.
    """

    def __init__(self, config: StrategyConfig = None):
        self.config = config or StrategyConfig(name=self.name)

    @property
    @abstractmethod
    def name(self) -> str:
        """Unique strategy name"""

    @property
    @abstractmethod
    def description(self) -> str:
        """Brief description of the strategy"""

    @abstractmethod
    def get_required_indicators(self) -> List[str]:
        """
        List of indicator names required by this strategy.
        Should match names from IndicatorCalculator.
        """

    @abstractmethod
    def generate_signal(
        self,
        symbol: str,
        snapshot: 'MarketSnapshot',
        indicators: Dict[str, float]
    ) -> Optional[Signal]:
        """
        Generate trading signal based on current market state.

        Args:
            symbol: Stock symbol
            snapshot: Current market snapshot
            indicators: Pre-calculated indicator values

        Returns:
            Signal if conditions met, None otherwise
        """

    def validate_conditions(
        self,
        symbol: str,
        snapshot: 'MarketSnapshot'
    ) -> bool:
        """
        Pre-validation before signal generation.
        Override for strategy-specific validation.

        Returns:
            True if basic conditions are met for trading
        """
        # Check if strategy is enabled for this symbol
        if self.config.symbols and symbol not in self.config.symbols:
            return False

        # Check if we have minimum data
        if not snapshot.bars_1m or len(snapshot.bars_1m) < 20:
            return False

        # Check liquidity (bid-ask spread)
        if snapshot.bid > 0 and snapshot.ask > 0:
            spread_pct = (snapshot.ask - snapshot.bid) / snapshot.mid_price * 100
            if spread_pct > 0.5:  # Max 0.5% spread
                return False

        return True

    def calculate_stop_loss(
        self,
        entry_price: float,
        direction: SignalDirection,
        atr: float
    ) -> float:
        """Calculate stop loss price based on ATR"""
        mult = self.config.default_stop_atr_mult
        if direction == SignalDirection.LONG:
            return entry_price - (atr * mult)
        else:
            return entry_price + (atr * mult)

    def calculate_take_profit(
        self,
        entry_price: float,
        direction: SignalDirection,
        atr: float
    ) -> float:
        """Calculate take profit price based on ATR"""
        mult = self.config.default_target_atr_mult
        if direction == SignalDirection.LONG:
            return entry_price + (atr * mult)
        else:
            return entry_price - (atr * mult)

    def should_send_to_ai(self, signal: Signal) -> bool:
        """
        Determine if signal should be evaluated by AI.
        High confidence or large position = AI review.
        """
        if signal.confidence >= self.config.ai_threshold:
            return True

        if signal.suggested_size_pct and signal.suggested_size_pct >= 0.03:
            return True

        return False


